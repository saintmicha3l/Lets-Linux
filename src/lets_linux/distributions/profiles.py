PROFILES: dict[str, DistributionProfile] = {
    p.id: p for p in (DEBIAN, UBUNTU, FEDORA, ARCH, GENERIC)
}


def get_profile(profile_id: str) -> DistributionProfile:
    try:
        return PROFILES[profile_id]
    except KeyError:
        raise KeyError(
            f"unknown distribution profile {profile_id!r}; available: {', '.join(PROFILES)}"
        ) from None
